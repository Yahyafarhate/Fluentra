/** Generates docs/API.md from the live route tables, so the documentation can never drift from the code. */
import fs from "node:fs";
import { v1 } from "../src/server/routes/v1";
import { authRouter } from "../src/server/routes/auth";

const table = (title: string, intro: string, docs: Array<{ method: string; path: string; access: string; summary: string }>) =>
  `## ${title}\n\n${intro}\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n${docs.map((d) => `| \`${d.method}\` | \`${d.path.replace(/:(\w+)/g, "{$1}")}\` | ${d.access} | ${d.summary} |`).join("\n")}\n`;

const extra = [
  { method: "GET", path: "/api/health", access: "public", summary: "Liveness + database check (no secrets)" },
  { method: "GET", path: "/api/v1/stream?outletId=", access: "pos.access", summary: "Server-Sent Events: live `change` notifications for one outlet (PostgreSQL LISTEN/NOTIFY). 503 on serverless hosts — clients poll." },
  { method: "GET|POST", path: "/api/cron/tick", access: "`Authorization: Bearer $CRON_SECRET`", summary: "Deliver due outbox events (Fluentra sync) and housekeeping" },
];

const md = `# API reference

> Generated by \`npm run docs:api\` from the route tables in \`src/server/routes/*\`. Do not edit by hand.

**Conventions**

- JSON in/out. Errors: \`{ "error": { "code": "…", "message": "…", "details": … } }\` with HTTP 400/401/402/403/404/409/422/423/429/500/502.
- Authentication: HttpOnly session cookie \`cp_session\` (SameSite=Lax, Secure in production). POS sessions are bound to one outlet and lock after the outlet's idle time. Mutating requests must carry a same-origin \`Origin\` header (CSRF defense).
- Every endpoint checks its permission **on the server** (the “Access” column) and runs inside a PostgreSQL transaction scoped to the caller's organization (Row Level Security).
- **Idempotency**: order mutations accept an \`Idempotency-Key\` header (replayed responses, safe offline retries). Payments and refunds *require* an \`idempotencyKey\` field.
- Restricted actions (void a sent item, large/custom discounts, refunds, reopen, void order) return \`403 APPROVAL_REQUIRED\` unless the caller holds the authority; retry with \`approval: { employeeId, pin }\` of a supervisor.
- Payments: \`201\` succeeded, \`402\` declined (the declined attempt is recorded), \`202\` pending provider confirmation, \`422 PROVIDER_NOT_CONFIGURED\` when no card provider exists, \`502 PROVIDER_ERROR\` when the outcome is unknown (payment stays pending for reconciliation).

${table("Authentication", "Prefix `/api/auth`.", authRouter.docs)}
${table("POS & back-office API", "Prefix `/api/v1`.", v1.docs)}
${table("Other endpoints", "", extra)}
`;
fs.writeFileSync("docs/API.md", md);
console.log(`docs/API.md written (${v1.docs.length + authRouter.docs.length + extra.length} endpoints)`);
