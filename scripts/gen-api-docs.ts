/** Generates docs/API.md from the live route tables, so the documentation can never drift from the code. */
import fs from "node:fs";
import { v1 } from "../src/server/routes/v1";
import { publicRouter } from "../src/server/routes/public";
import { adminRouter } from "../src/server/routes/admin";
import { authRouter } from "../src/server/routes/auth";

const table = (title: string, intro: string, docs: Array<{ method: string; path: string; access: string; summary: string }>) =>
  `## ${title}\n\n${intro}\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n${docs.map((d) => `| \`${d.method}\` | \`${d.path.replace(/:(\w+)/g, "{$1}")}\` | ${d.access} | ${d.summary} |`).join("\n")}\n`;

const extra = [
  { method: "GET", path: "/api/health", access: "public", summary: "Liveness + database check (no secrets)" },
  { method: "GET", path: "/api/v1/stream?locationId=", access: "dashboard.view", summary: "Server-Sent Events: live `change` notifications for one location (PostgreSQL LISTEN/NOTIFY)" },
  { method: "GET", path: "/api/files/{id}", access: "public", summary: "Serve an uploaded branding image (magic-byte validated, `nosniff`, sandboxed CSP)" },
  { method: "POST", path: "/api/webhooks/delivery", access: "HMAC signature (`x-signature`)", summary: "Provider delivery / engagement receipts. Only source that may mark messages delivered/opened/clicked" },
  { method: "POST", path: "/api/cron/tick", access: "`Authorization: Bearer $CRON_SECRET`", summary: "Scheduler tick: enqueue automations, scheduled campaigns, retention; run due jobs" },
];

const md = `# API reference

> Generated by \`npm run docs:api\` from the route tables in \`src/server/routes/*\`. Do not edit by hand.

**Conventions**

- JSON in/out. Errors: \`{ "error": { "code": "…", "message": "…", "details": … } }\` with HTTP 400/401/402/403/404/409/422/429/500.
- Authentication: HttpOnly session cookie \`fl_session\` (SameSite=Lax, Secure in production). Mutating requests must carry a same-origin \`Origin\` header (CSRF defense).
- Every tenant endpoint runs the permission check **on the server** (the "Access" column) and executes inside a PostgreSQL transaction scoped to the caller's organization (Row Level Security).
- Validation: Zod schemas; failures return \`422 VALIDATION_ERROR\` with per-field \`details\`.
- Public endpoints are rate limited per IP (and per contact for bookings) and return \`429\` with \`Retry-After\`.
- Reservation conflicts return \`409\` (\`NO_AVAILABILITY\`, \`TABLE_CONFLICT\`, \`DUPLICATE_RESERVATION\`, \`INVALID_TRANSITION\`, …). Plan limits return \`402 PLAN_LIMIT\`; plan-gated features \`403 FEATURE_NOT_IN_PLAN\`.

${table("Authentication", "Prefix `/api/auth`.", authRouter.docs)}
${table("Tenant API (staff)", "Prefix `/api/v1`. “any member” = any authenticated member of the active organization.", v1.docs)}
${table("Public API (guests)", "Prefix `/api/public`. No authentication; rate limited; never exposes internal notes, staff, table names or other tenants.", publicRouter.docs)}
${table("Platform administration", "Prefix `/api/admin`. Requires \`users.is_super_admin\`. Tenant roles (even owners) are rejected.", adminRouter.docs)}
${table("Other endpoints", "", extra)}
`;
fs.writeFileSync("docs/API.md", md);
console.log(`docs/API.md written (${v1.docs.length + publicRouter.docs.length + adminRouter.docs.length + authRouter.docs.length + extra.length} endpoints)`);
